"""Ошибки бизнес-логики.

Сервисы бросают эти исключения, роутеры переводят их в HTTP-коды.
Сервис не знает про HTTP, поэтому не может бросить HTTPException сам.
Все наследуются от встроенного LookupError — это стандартный класс Python
для ситуации «искали и не нашли».
"""


class ArticleNotFoundError(LookupError):
    """Статья не найдена. Для публичных ручек — в том числе если она черновик."""


class TagNotFoundError(LookupError):
    """Тега с таким идентификатором не существует."""
