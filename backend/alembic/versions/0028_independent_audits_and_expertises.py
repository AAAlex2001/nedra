def separate_service_tables() -> None:
    """Перенести заказчика и дату в каждую услугу."""

    for table in ("audits", "expertises"):
        execute_statements(f"""
            ALTER TABLE {table}
                ADD COLUMN customer_id integer REFERENCES users(id) ON DELETE RESTRICT,
                ADD COLUMN customer_type varchar(16),
                ADD COLUMN comment text,
                ADD COLUMN created_at timestamptz;
            UPDATE {table} AS service
            SET customer_id = source.customer_id,
                customer_type = CASE WHEN person.request_id IS NOT NULL THEN 'individual'
                                     ELSE company.customer_type END,
                comment = source.comment,
                created_at = source.created_at
            FROM service_requests AS source
            LEFT JOIN request_companies AS company ON company.request_id = source.id
            LEFT JOIN request_individuals AS person ON person.request_id = source.id
            WHERE source.id = service.request_id;
            ALTER TABLE {table}
                ALTER COLUMN customer_id SET NOT NULL,
                ALTER COLUMN customer_type SET NOT NULL,
                ALTER COLUMN created_at SET NOT NULL,
                ALTER COLUMN created_at SET DEFAULT now(),
                DROP CONSTRAINT {table}_request_id_fkey;
            ALTER TABLE {table} RENAME COLUMN request_id TO id;
            ALTER TABLE {table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            SELECT setval(pg_get_serial_sequence('{table}', 'id'),
                          COALESCE((SELECT max(id) FROM {table}), 1),
                          EXISTS (SELECT 1 FROM {table}));
            CREATE INDEX ix_{table}_customer_id ON {table}(customer_id);
        """)

