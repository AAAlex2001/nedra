def separate_customer_details() -> None:
    """Разделить реквизиты организаций."""

    for feature, table in (("audit", "audits"), ("expertise", "expertises")):
        execute_statements(f"""
            CREATE TABLE {feature}_companies (LIKE request_companies INCLUDING DEFAULTS);
            INSERT INTO {feature}_companies
            SELECT company.* FROM request_companies AS company
            JOIN {table} AS service ON service.id = company.request_id;
            ALTER TABLE {feature}_companies DROP COLUMN customer_type;
            ALTER TABLE {feature}_companies RENAME COLUMN request_id TO {feature}_id;
            ALTER TABLE {feature}_companies
                ADD PRIMARY KEY ({feature}_id),
                ADD FOREIGN KEY ({feature}_id) REFERENCES {table}(id) ON DELETE CASCADE;
        """)

    op.drop_table("request_companies")
    op.rename_table("request_individuals", "expertise_individuals")
    op.drop_constraint("expertise_individuals_expertise_id_fkey", "expertise_individuals", type_="foreignkey")
    op.alter_column("expertise_individuals", "request_id", new_column_name="expertise_id")
    op.create_foreign_key(
        "expertise_individuals_expertise_id_fkey", "expertise_individuals", "expertises",
        ["expertise_id"], ["id"], ondelete="CASCADE",
    )


def separate_documents() -> None:
    """Разделить документы с сохранением номеров и путей."""

    for feature, table in (("audit", "audits"), ("expertise", "expertises")):
        other_feature = "expertise" if feature == "audit" else "audit"
        execute_statements(f"""
            CREATE TABLE {feature}_documents (LIKE request_documents INCLUDING DEFAULTS);
            INSERT INTO {feature}_documents
            SELECT document.* FROM request_documents AS document
            JOIN {table} AS service ON service.id = document.request_id;
            ALTER TABLE {feature}_documents
                DROP COLUMN {other_feature}_remark_id,
                ALTER COLUMN uploaded_by DROP NOT NULL,
                ALTER COLUMN id DROP DEFAULT;
            ALTER TABLE {feature}_documents RENAME COLUMN request_id TO {feature}_id;
            ALTER TABLE {feature}_documents RENAME COLUMN {feature}_remark_id TO remark_id;
            ALTER TABLE {feature}_documents
                ADD PRIMARY KEY (id),
                ADD FOREIGN KEY ({feature}_id) REFERENCES {table}(id) ON DELETE CASCADE,
                ADD FOREIGN KEY (remark_id) REFERENCES {feature}_remarks(id) ON DELETE CASCADE,
                ADD FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL,
                ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
            SELECT setval(pg_get_serial_sequence('{feature}_documents', 'id'),
                          COALESCE((SELECT max(id) FROM {feature}_documents), 1),
                          EXISTS (SELECT 1 FROM {feature}_documents));
            CREATE INDEX ix_{feature}_documents_{feature}_id ON {feature}_documents({feature}_id);
            CREATE INDEX ix_{feature}_documents_remark_id ON {feature}_documents(remark_id);
        """)

    op.drop_table("request_documents")


def separate_payment_stages() -> None:
    """Разделить оплату этапов."""

    for feature, table in (("audit", "audits"), ("expertise", "expertises")):
        execute_statements(f"""
            CREATE TABLE {feature}_payments (
                {feature}_id integer REFERENCES {table}(id) ON DELETE CASCADE,
                stage varchar(16),
                payment_id integer REFERENCES payments(id) ON DELETE SET NULL,
                paid_at timestamptz,
                PRIMARY KEY ({feature}_id, stage),
                CONSTRAINT ck_{feature}_payments_stage CHECK (stage IN ('advance', 'final'))
            );
            INSERT INTO {feature}_payments
            SELECT payment.* FROM request_payments AS payment
            JOIN {table} AS service ON service.id = payment.request_id;
            CREATE INDEX ix_{feature}_payments_payment_id ON {feature}_payments(payment_id);
        """)

    op.drop_table("request_payments")


def update_contract_links() -> None:
    """Привязать договор к конкретной услуге."""

    execute_statements("""
        ALTER TABLE contracts
            ADD COLUMN id integer GENERATED BY DEFAULT AS IDENTITY,
            ADD COLUMN audit_id integer UNIQUE REFERENCES audits(id) ON DELETE CASCADE,
            ADD COLUMN expertise_id integer UNIQUE REFERENCES expertises(id) ON DELETE CASCADE;
        UPDATE contracts SET audit_id = request_id WHERE request_id IN (SELECT id FROM audits);
        UPDATE contracts SET expertise_id = request_id WHERE request_id IN (SELECT id FROM expertises);
        ALTER TABLE contracts DROP COLUMN request_id;
        ALTER TABLE contracts ADD PRIMARY KEY (id),
            ADD CONSTRAINT ck_contract_service CHECK (num_nonnulls(expertise_id, audit_id) = 1);
    """)


